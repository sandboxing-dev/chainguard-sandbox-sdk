/** A sandbox's state. */
export interface SandboxInfo {
  sandboxId: string;
  name: string;
  displayName: string;
  state: "creating" | "running" | "paused" | "stopped";
  region: string;
  createdAt?: Date;
  /** When a paused sandbox is discarded, if set. */
  expiresAt?: Date;
  cpuCount: number;
  memoryMB: number;
}

function info(s: Session): SandboxInfo {
  const state = s.phase === Phase.CREATING ? "creating" : s.phase === Phase.ATTACHED || s.phase === Phase.IDLE ? "running" : s.phase === Phase.PARKED ? "paused" : "stopped";
  return {
    sandboxId: s.shortId,
    name: s.name,
    displayName: s.displayName,
    state,
    region: s.region,
    createdAt: s.createTime ? timestampDate(s.createTime) : undefined,
    expiresAt: s.expireTime ? timestampDate(s.expireTime) : undefined,
    cpuCount: s.maxResourceClass?.cpus ?? 0,
    memoryMB: Number(s.maxResourceClass?.memoryMib ?? 0n),
  };
}

class PlacementError extends Error {}

/**
 * Polls until the guest has started. limitMs bounds the whole wait, each GetSession call included:
 * a call that stalls is cut off at the deadline, and an answer that arrives after it is never
 * reported as a start in time.
 */
async function waitStarted(c: Client, name: string, limitMs: number): Promise<Session> {
  const t0 = Date.now();
  const deadline = t0 + limitMs;
  let last: Session | undefined;
  const expired = () => new TimeoutError(`the guest did not start within ${limitMs} ms${last ? ` (${Phase[last.phase]}: ${last.message})` : ""}`);
  for (;;) {
    const remaining = deadline - Date.now();
    if (remaining <= 0) throw expired();
    const signal = AbortSignal.timeout(remaining);
    let s: Session;
    try {
      s = await getSession(c, name, signal);
    } catch (e) {
      if (signal.aborted) throw expired();
      throw wrap(e);
    }
    if (Date.now() > deadline) throw expired();
    last = s;
    if (s.guestStartedTime) return s;
    if (s.message.includes("starting guest failed") && Date.now() - t0 > timings.placementGraceMs) throw new PlacementError(s.message);
    await Bun.sleep(Math.max(Math.min(timings.startPollMs, deadline - Date.now()), 0));
  }
}

/**
 * Sends the delete request and waits until the session is gone. Resolves false if there was none;
 * rejects with TimeoutError if it can't be confirmed gone.
 */
async function deleteAndWait(c: Client, name: string): Promise<boolean> {
  try {
    await deleteSession(c, name);
  } catch (e) {
    if (e instanceof ConnectError && e.code === Code.NotFound) return false;
    throw wrap(e);
  }
  // Deletion is asynchronous (the session disappears 1-8 s later). Each check runs under the
  // deadline, so a stalled call can't stretch the wait.
  const waitMs = timings.killWaitMs;
  const deadline = Date.now() + waitMs;
  let failure: unknown;
  for (;;) {
    const remaining = deadline - Date.now();
    if (remaining <= 0) break;
    const signal = AbortSignal.timeout(remaining);
    try {
      await getSession(c, name, signal);
      failure = undefined;
    } catch (e) {
      if (e instanceof ConnectError && e.code === Code.NotFound) return true;
      failure = signal.aborted ? undefined : e;
    }
    await Bun.sleep(Math.max(Math.min(timings.killPollMs, deadline - Date.now()), 0));
  }
  if (failure !== undefined) throw new TimeoutError(`could not confirm the sandbox is gone within ${waitMs} ms (last check: ${(wrap(failure) as Error).message})`);
  throw new TimeoutError(`the sandbox still exists ${waitMs} ms after the delete request`);
}

/** Passes a chunk of bytes to a text callback, holding back an incomplete UTF-8 character; with no chunk, flushes. */
function emit(decoder: TextDecoder, cb: ((data: string) => void) | undefined, chunk?: Uint8Array): void {
  if (!cb) return;
  const s = chunk ? decoder.decode(chunk, { stream: true }) : decoder.decode();
  if (s) cb(s);
}

/** Complete the required first attach with an empty tree (exec is refused until a shell attach has uploaded the workspace). */
async function emptyUpload(c: Client, name: string): Promise<void> {
  try {
    await completeFirstAttach(c, name, { timeoutMs: 120_000 });
  } catch (e) {
    // Ending without the upload accepted (timeout, the stream ended, or another client took over) is a
    // TimeoutError, as before; an RPC error is a SandboxError.
    if (e instanceof FirstAttachError) throw new TimeoutError("the first attach did not complete");
    throw new SandboxError(`completing the first attach: ${(wrap(e) as Error).message}`);
  }
}

/**
 * A sandbox: one Chainguard Workspaces session with your packages.
 * Commands run one at a time per sandbox.
 */
export class Sandbox {
  /** Short sandbox ID (8 hex characters), usable with Sandbox.connect. */
  readonly sandboxId: string;
  /** Full resource name (instances/<org>/sessions/<id>). */
  readonly name: string;
  /** Run commands. */
  readonly commands: Commands;
  /** Read and write files. */
  readonly files: Filesystem;
  /** The underlying Workspaces client, for anything this package doesn't wrap. */
  readonly client: Client;
  /** @internal */
  readonly envs: Record<string, string>;

  /** @internal */
  protected constructor(client: Client, s: Session, envs?: Record<string, string>) {
    this.client = client;
    this.sandboxId = s.shortId;
    this.name = s.name;
    this.envs = { ...envs };
    this.commands = new Commands(this);
    this.files = new Filesystem(this);
  }

  /**
   * Create a sandbox; resolves when it can run commands (about 8–20 s). A session
   * the plane places on a host that never starts is deleted and recreated (up to 3
   * attempts). On failure nothing is left behind.
   */
  static async create(opts: SandboxOpts = {}): Promise<Sandbox> {
    const name = opts.name ?? "sandbox";
    if (!name || /[/\n]/.test(name)) throw new Error("name must be non-empty without '/' or newlines");
    const c = opts.client ?? new Client({ instance: opts.instance });
    const doc = environmentDocument(opts);
    let last: unknown;
    for (let attempt = 0; attempt < 3; attempt++) {
      const req = opts.source ? repositorySession(opts.source.url, opts.source.revision ?? "") : workspaceSession(LABEL_PREFIX + name, "", "", doc);
      if (opts.source && req.environment.case === "source") req.environment.value.fallbackDocument = doc;
      let s: Session;
      try {
        s = await createSession(c, req);
      } catch (e) {
        throw wrap(e);
      }
      try {
        s = await waitStarted(c, s.name, opts.startTimeoutMs ?? 180_000);
        if (s.workspacePending) await emptyUpload(c, s.name);
        return new Sandbox(c, s, opts.envs);
      } catch (e) {
        await deleteSession(c, s.name).catch(() => {});
        if (e instanceof PlacementError) {
          last = e;
          continue;
        }
        throw e;
      }
    }
    throw new SandboxError(`the plane could not start a guest in 3 attempts: ${(last as Error)?.message}`);
  }

  /** A handle to an existing sandbox (short ID, display name or resource name). A paused sandbox resumes on its first command. */
  static async connect(sandboxId: string, opts: ConnectOpts = {}): Promise<Sandbox> {
    const c = opts.client ?? new Client({ instance: opts.instance });
    let s: Session;
    try {
      s = await resolveSession(c, sandboxId);
    } catch (e) {
      if (e instanceof LibNotFound) throw new SandboxNotFoundError("sandbox", sandboxId);
      throw wrap(e);
    }
    if (s.workspacePending) await emptyUpload(c, s.name);
    return new Sandbox(c, s, opts.envs);
  }

  /** The sandboxes this package created in the instance. */
  static async list(opts: ConnectOpts = {}): Promise<SandboxInfo[]> {
    const c = opts.client ?? new Client({ instance: opts.instance });
    try {
      return (await listSessions(c)).filter((s) => s.environment.case === "workspace" && s.environment.value.label.startsWith(LABEL_PREFIX)).map(info);
    } catch (e) {
      throw wrap(e);
    }
  }

  /**
   * Delete a sandbox by ID (short ID, display name or resource name). Resolves false if there was
   * none. Unlike connect it does not attach to the sandbox first, so it also deletes one that never
   * started or cannot be attached to. Rejects as the instance method does.
   */
  static async kill(sandboxId: string, opts: ConnectOpts = {}): Promise<boolean> {
    const c = opts.client ?? new Client({ instance: opts.instance });
    let s: Session;
    try {
      s = await resolveSession(c, sandboxId);
    } catch (e) {
      if (e instanceof LibNotFound || (e instanceof ConnectError && e.code === Code.NotFound)) return false;
      throw wrap(e);
    }
    return deleteAndWait(c, s.name);
  }

  /**
   * Delete the sandbox and everything in it; resolves once it is gone, so the session slot is free.
   * Resolves false if it was already gone. Rejects with TimeoutError if the sandbox still exists
   * 30 s after the delete request (or that can't be confirmed): deletion was requested, but the
   * slot may not be free yet.
   */
  async kill(): Promise<boolean> {
    return deleteAndWait(this.client, this.name);
  }

  /** `await using sbx = await Sandbox.create()` kills the sandbox at the end of the scope. */
  async [Symbol.asyncDispose](): Promise<void> {
    await this.kill();
  }

  /** Snapshot (memory and disk) and stop the sandbox. Processes, including background commands, continue on the next call. */
  async pause(): Promise<void> {
    try {
      await parkSession(this.client, this.name);
    } catch (e) {
      throw wrap(e);
    }
  }

  /** Hold the sandbox running (not parked when idle) for this long. There is no hard deadline: an idle sandbox parks after about 10 minutes. */
  async keepAlive(ms: number): Promise<void> {
    try {
      await heartbeatSession(this.client, this.name, ms);
    } catch (e) {
      throw wrap(e);
    }
  }

  async getInfo(): Promise<SandboxInfo> {
    try {
      return info(await getSession(this.client, this.name));
    } catch (e) {
      if (e instanceof ConnectError && e.code === Code.NotFound) throw new SandboxNotFoundError("sandbox", this.sandboxId);
      throw wrap(e);
    }
  }

  async isRunning(): Promise<boolean> {
    try {
      return (await this.getInfo()).state === "running";
    } catch (e) {
      if (e instanceof SandboxNotFoundError) return false;
      throw e;
    }
  }

  /** @internal Prefix argv with `env K=V ...` for the merged environment. */
  envArgv(extra: Record<string, string> | undefined, argv: string[]): string[] {
    const merged = { ...this.envs, ...extra };
    const keys = Object.keys(merged).sort();
    return keys.length ? ["env", ...keys.map((k) => `${k}=${merged[k]}`), ...argv] : argv;
  }

  /** @internal Run argv unwrapped. */
  async exec(argv: string[], o: { stdin?: Uint8Array; timeoutMs?: number; stdout?: (b: Uint8Array) => void; stderr?: (b: Uint8Array) => void } = {}): Promise<ExecResult> {
    try {
      return await exec(this.client, this.name, argv, { noDir: true, ...o });
    } catch (e) {
      throw wrap(e);
    }
  }

  /** @internal Run a script, returning stdout, exit code and stderr. */
  async script(script: string, args: string[], stdin?: Uint8Array, timeoutMs = 0): Promise<{ out: Uint8Array; code: number; err: Uint8Array }> {
    const out: Uint8Array[] = [];
    const err: Uint8Array[] = [];
    const res = await this.exec(["sh", "-c", script, "_", ...args], { stdin, timeoutMs, stdout: (b) => out.push(b), stderr: (b) => err.push(b) });
    return { out: Buffer.concat(out), code: res.exitCode, err: Buffer.concat(err) };
  }
}

