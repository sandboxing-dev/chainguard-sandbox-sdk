export type FileType = "file" | "dir" | "symlink";

export interface WriteInfo {
  name: string;
  path: string;
  type: FileType;
}

export interface EntryInfo {
  name: string;
  path: string;
  type: FileType;
  size: number;
  /** Permission bits, e.g. 0o644. */
  mode: number;
  /** e.g. "rwxr-xr-x". */
  permissions: string;
  owner: string;
  group: string;
  modifiedTime: Date;
  symlinkTarget?: string;
}

/** One file for files.write([...]). */
export interface WriteEntry {
  path: string;
  data: string | Uint8Array;
  /** Default 0o644. */
  mode?: number;
}

const permString = (mode: number) => [..."rwxrwxrwx"].map((c, i) => (mode & (1 << (8 - i)) ? c : "-")).join("");

/** @internal Decode stat lines: "<type>\t<size> <mode> <user> <group> <mtime>\t<link>\t<path>". */
export function parseEntries(out: Uint8Array, base = ""): EntryInfo[] {
  const es: EntryInfo[] = [];
  for (const line of dec.decode(out).split("\n")) {
    if (!line) continue;
    const f = line.split("\t");
    const st = f.length >= 4 ? f[1]!.trim().split(/\s+/) : [];
    if (st.length !== 5) throw new SandboxError(`malformed entry ${JSON.stringify(line)}`);
    const name = f.slice(3).join("\t");
    const path = base ? `${base.replace(/\/$/, "")}/${name}` : name;
    const mode = parseInt(st[1]!, 8) & 0o777;
    es.push({
      name: basename(path),
      path,
      type: f[0] as FileType,
      size: Number(st[0]),
      mode,
      permissions: permString(mode),
      owner: st[2]!,
      group: st[3]!,
      modifiedTime: new Date(Number(st[4]) * 1000),
      symlinkTarget: f[2] || undefined,
    });
  }
  return es;
}

/** `sbx.files`: the sandbox filesystem. Relative paths resolve against /work. */
export class Filesystem {
  constructor(private readonly sbx: Sandbox) {}

  private async run(script: string, args: string[], stdin?: Uint8Array, path = args[0] ?? ""): Promise<Uint8Array> {
    const { out, code, err } = await this.sbx.script(script, args, stdin);
    if (code !== 0) throw scriptError(code, path, err);
    return out;
  }

  /** A file's contents as text (default), bytes or a Blob. Rejects with FileNotFoundError if missing. */
  read(path: string, opts?: { format?: "text" }): Promise<string>;
  read(path: string, opts: { format: "bytes" }): Promise<Uint8Array>;
  read(path: string, opts: { format: "blob" }): Promise<Blob>;
  async read(path: string, opts: { format?: "text" | "bytes" | "blob" } = {}): Promise<string | Uint8Array | Blob> {
    const b = await this.run(S.READ_SCRIPT, [guestPath(path)]);
    return opts.format === "bytes" ? b : opts.format === "blob" ? new Blob([b as Uint8Array<ArrayBuffer>]) : dec.decode(b);
  }

  /**
   * Create or replace a file atomically (mode 0644), creating parent directories; any
   * size works (over 15 MiB is staged in pieces). With an array, writes several files
   * in one upload.
   */
  write(path: string, data: string | Uint8Array | ArrayBuffer | Blob): Promise<WriteInfo>;
  write(files: WriteEntry[]): Promise<WriteInfo[]>;
  async write(pathOrFiles: string | WriteEntry[], data?: string | Uint8Array | ArrayBuffer | Blob): Promise<WriteInfo | WriteInfo[]> {
    if (Array.isArray(pathOrFiles)) return this.writeFiles(pathOrFiles);
    const b =
      typeof data === "string" ? enc.encode(data) : data instanceof Blob ? new Uint8Array(await data.arrayBuffer()) : data instanceof ArrayBuffer ? new Uint8Array(data) : (data ?? new Uint8Array());
    return this.writeBytes(pathOrFiles, b, 0o644);
  }

  private async writeBytes(path: string, b: Uint8Array, mode: number): Promise<WriteInfo> {
    const gp = guestPath(path);
    if (b.length <= S.MAX_STDIN_PER_EXEC) {
      try {
        await writeFile(this.sbx.client, this.sbx.name, gp, b, mode);
      } catch (e) {
        if (e instanceof LibExitError && e.exitCode === 21) throw new InvalidPathError(gp, "is a directory");
        if (e instanceof LibExitError) throw new SandboxError(e.message);
        throw wrap(e);
      }
    } else {
      const tmp = await this.stage(b);
      await this.run(S.FINISH_SCRIPT, [tmp, gp, (mode & 0o777).toString(8)], undefined, gp);
    }
    return { name: basename(gp), path: gp, type: "file" };
  }

  private async stage(b: Uint8Array): Promise<string> {
    const tmp = `${S.STATE_DIR}/upload/${randomBytes(8).toString("hex")}`;
    for (let off = 0; off === 0 || off < b.length; off += S.MAX_STDIN_PER_EXEC) {
      await this.run(S.APPEND_SCRIPT, [tmp, off === 0 ? "trunc" : "append"], b.subarray(off, off + S.MAX_STDIN_PER_EXEC), tmp);
      if (off + S.MAX_STDIN_PER_EXEC >= b.length) break;
    }
    return tmp;
  }

  private async untar(tgz: Uint8Array, dir: string): Promise<void> {
    if (tgz.length > S.MAX_STDIN_PER_EXEC) await this.run(S.UNTAR_SCRIPT, [await this.stage(tgz), dir], undefined, dir);
    else await this.run(S.UNTAR_SCRIPT, ["-", dir], tgz, dir);
  }

  /** Write several files in one upload, creating parent directories. */
  async writeFiles(files: WriteEntry[]): Promise<WriteInfo[]> {
    const now = Date.now() / 1000;
    const entries: TarEntry[] = [];
    const infos: WriteInfo[] = [];
    for (const f of files) {
      const gp = guestPath(f.path);
      if (gp === "/") throw new Error(`invalid file path ${JSON.stringify(f.path)}`);
      entries.push({ name: gp.slice(1), data: typeof f.data === "string" ? enc.encode(f.data) : f.data, mode: (f.mode ?? 0o644) & 0o777 || 0o644, mtime: now });
      infos.push({ name: basename(gp), path: gp, type: "file" });
    }
    await this.untar(Bun.gzipSync(tarBytes(entries)), "/");
    return infos;
  }

  /** Entries of a directory (one level), sorted by name. */
  async list(path = "."): Promise<EntryInfo[]> {
    const gp = guestPath(path);
    return parseEntries(await this.run(S.LIST_DIR_SCRIPT, [gp]), gp);
  }

  /** Whether a path exists (a dangling symlink counts). */
  async exists(path: string): Promise<boolean> {
    return (await this.sbx.script(S.EXISTS_SCRIPT, [guestPath(path)])).code === 0;
  }

  /** Describe a path without following a final symlink. */
  async getInfo(path: string): Promise<EntryInfo> {
    const es = parseEntries(await this.run(S.INFO_SCRIPT, [guestPath(path)]));
    if (es.length !== 1) throw new SandboxError(`unexpected stat output for ${path}`);
    return es[0]!;
  }

  /** Create a directory and its parents. Resolves false if it already existed. */
  async makeDir(path: string): Promise<boolean> {
    return dec.decode(await this.run(S.MAKE_DIR_SCRIPT, [guestPath(path)])).trim() === "1";
  }

  /** Delete a file or directory tree. Rejects with FileNotFoundError if missing. */
  async remove(path: string): Promise<void> {
    await this.run(S.REMOVE_SCRIPT, [guestPath(path)]);
  }

  /** Move a file or directory (creating the destination's parents); describes the result. */
  async rename(oldPath: string, newPath: string): Promise<EntryInfo> {
    const es = parseEntries(await this.run(S.RENAME_SCRIPT, [guestPath(oldPath), guestPath(newPath)]));
    if (es.length !== 1) throw new SandboxError(`unexpected stat output for ${newPath}`);
    return es[0]!;
  }

  /** Copy a local file into the sandbox (keeping its permission bits). */
  async upload(localPath: string, remotePath: string): Promise<WriteInfo> {
    return this.writeBytes(remotePath, readFileSync(localPath), lstatSync(localPath).mode & 0o777);
  }

  /** Copy a file from the sandbox, creating local parent directories. */
  async download(remotePath: string, localPath: string): Promise<void> {
    const b = await this.read(remotePath, { format: "bytes" });
    mkdirSync(dirname(localPath), { recursive: true });
    writeFileSync(localPath, b);
  }

  /** Copy a local directory tree into remoteDir (created if missing) as one tar. Symlinks are copied as links; files are owned by root. */
  async uploadDir(localDir: string, remoteDir: string): Promise<void> {
    await this.untar(tarGzDir(localDir), guestPath(remoteDir));
  }

  /**
   * Copy a directory tree from the sandbox into localDir. Nothing is written outside it: absolute
   * names and ".." are refused, an entry is never written through a symbolic link, and a link that
   * leads outside localDir (directly or through other links) is removed and reported as an error.
   */
  async downloadDir(remoteDir: string, localDir: string): Promise<void> {
    extractTarGz(await this.run(S.TAR_SCRIPT, [guestPath(remoteDir)]), localDir);
  }
}

