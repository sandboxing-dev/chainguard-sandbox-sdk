/** The toolchain a sandbox gets by default: a shell, core tools, git, curl, jq, Python and Node.js (Chainguard package names). */
export const DEFAULT_PACKAGES: readonly string[] = ["bash", "coreutils", "curl", "git", "jq", "python-3.13", "nodejs-22"];
/** Where commands run and relative paths resolve. */
export const DEFAULT_WORKDIR = "/work";
/** Default limit for a foreground command (ms). 0 means no limit. */
export const DEFAULT_COMMAND_TIMEOUT_MS = 60_000;

const LABEL_PREFIX = "/chainguard-sandbox/";
const enc = new TextEncoder();
const dec = new TextDecoder();

function guestPath(p?: string): string {
  const joined = !p ? DEFAULT_WORKDIR : p.startsWith("/") ? p : `${DEFAULT_WORKDIR}/${p}`;
  const out: string[] = [];
  for (const seg of joined.split("/")) {
    if (seg === "" || seg === ".") continue;
    if (seg === "..") out.pop();
    else out.push(seg);
  }
  return "/" + out.join("/");
}

const basename = (p: string) => p.slice(p.lastIndexOf("/") + 1);

function wrap(e: unknown): unknown {
  if (e instanceof LibOutcomeUnknown) return new OutcomeUnknownError(e.message, e.cause);
  if (isGuestHeld(e)) return new SandboxBusyError(`another client (an interactive shell) is attached to this sandbox; commands run once it detaches (${(e as ConnectError).rawMessage})`);
  if (e instanceof ConnectError) {
    if (e.code === Code.ResourceExhausted) return new LimitReachedError(`session limit reached; kill an existing sandbox first (${e.rawMessage})`);
    if (e.code === Code.NotFound) return new SandboxNotFoundError("sandbox", e.rawMessage);
    return new SandboxError(`${Code[e.code]}: ${e.rawMessage}`);
  }
  return e;
}

function scriptError(code: number, path: string, stderr: Uint8Array): SandboxError {
  if (code === S.EXIT_NOT_FOUND) return new FileNotFoundError("path", path);
  if (code === S.EXIT_IS_DIR) return new InvalidPathError(path, "is a directory");
  if (code === S.EXIT_NOT_DIR) return new InvalidPathError(path, "not a directory");
  return new SandboxError(`${path}: ${dec.decode(stderr).trim() || `exit ${code}`}`);
}

const yamlString = (s: string) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n")}"`;

/** The environment document Sandbox.create sends for these options. */
export function environmentDocument(o: Pick<SandboxOpts, "packages" | "egress" | "egressPolicy" | "document"> = {}): Uint8Array {
  if (o.document !== undefined) return typeof o.document === "string" ? enc.encode(o.document) : o.document;
  const pkgs = o.packages ?? DEFAULT_PACKAGES;
  const hosts = o.egress ?? ["*"];
  const lines = ["# Generated by chainguard-sandbox-sdk.", "version: 1", "environment:", "  packages:", ...pkgs.map((p) => `    - ${yamlString(p)}`)];
  lines.push("checks:", "  develop:", "    network:", `      egress:${hosts.length ? "" : " []"}`, ...hosts.map((h) => `        - ${yamlString(h)}`));
  lines.push(`      policy: ${yamlString(o.egressPolicy ?? "deny")}`);
  return enc.encode(lines.join("\n") + "\n");
}

/** Options for Sandbox.create. */
export interface SandboxOpts {
  /** Chainguard package names (default DEFAULT_PACKAGES). Unknown packages fail create. */
  packages?: readonly string[];
  /** Environment variables for every command (kept client-side, on this handle). */
  envs?: Record<string, string>;
  /** Label; the display name becomes `<name>/<word-word>`. Default "sandbox". */
  name?: string;
  /** Outbound allowlist (hostnames; "*" allows all). Default ["*"]. Cloud metadata, loopback and private ranges are always blocked. */
  egress?: readonly string[];
  /** What happens outside the allowlist: "deny" (refuse the connection, default) or "destroy" (stop the sandbox). */
  egressPolicy?: "deny" | "destroy";
  /** A full environment document instead of packages/egress. */
  document?: Uint8Array | string;
  /** Start from a GitHub repository (cloned into /work) instead of an empty tree. */
  source?: { url: string; revision?: string };
  /** How long to wait for the guest to start (ms, default 180000). */
  startTimeoutMs?: number;
  /** An existing client; by default one is created with the default login and the organization from `instance`. */
  client?: Client;
  /**
   * The organization ID (used when `client` is unset). If unset, $CHAINCTL_SANDBOX_INSTANCE is used;
   * if that's empty too, the organization is auto-detected when you belong to exactly one
   * ($CHAINGUARD_SANDBOX_NO_DETECT_INSTANCE=1 turns that off). List IDs with listOrganizations(),
   * `chainguard-sandbox orgs` or `chainctl iam organizations list`.
   */
  instance?: string;
}

