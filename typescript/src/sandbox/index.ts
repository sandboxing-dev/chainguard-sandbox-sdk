/** Options for commands.run. */
export interface CommandStartOpts {
  /** Working directory (default /work; relative paths resolve against /work). */
  cwd?: string;
  /** Added to the sandbox-level envs. */
  envs?: Record<string, string>;
  /** Kill the command after this long (ms, default 60000; 0 = no limit). Foreground only. */
  timeoutMs?: number;
  /** Sent to the command, then closed (at most 16 MiB). Foreground only. */
  stdin?: string | Uint8Array;
  /**
   * Output callbacks, called as data arrives. A character whose bytes arrive in two pieces is
   * delivered whole, with the later piece. Foreground only (for background commands, pass them to handle.wait()).
   */
  onStdout?: (data: string) => void;
  onStderr?: (data: string) => void;
  /** Start detached and resolve with a CommandHandle at once. */
  background?: boolean;
}

/** A background command, as listed by commands.list(). */
export interface ProcessInfo {
  pid: number;
  id: string;
  cmd: string;
  running: boolean;
  exitCode?: number;
}

/** `sbx.commands`: run commands in the sandbox. */
export class Commands {
  constructor(private readonly sbx: Sandbox) {}

  /**
   * Run a command and wait for it. `cmd` is a string (run with bash, so shell syntax
   * works) or an argv array (no shell). Rejects with CommandExitError on a non-zero
   * exit, TimeoutError after timeoutMs, FileNotFoundError if cwd is missing.
   * With `background: true`, resolves with a CommandHandle as soon as it starts.
   */
  run(cmd: string | string[], opts: CommandStartOpts & { background: true }): Promise<CommandHandle>;
  run(cmd: string | string[], opts?: CommandStartOpts & { background?: false }): Promise<CommandResult>;
  async run(cmd: string | string[], opts: CommandStartOpts = {}): Promise<CommandResult | CommandHandle> {
    const argv = typeof cmd === "string" ? ["bash", "-lc", cmd] : [...cmd];
    if (argv.length === 0) throw new Error("empty command");
    if (opts.background) return this.start(argv, opts);
    const stdin = typeof opts.stdin === "string" ? enc.encode(opts.stdin) : opts.stdin;
    if (stdin && stdin.length > 16 << 20) throw new Error(`stdin is ${stdin.length} bytes; the limit is 16 MiB (write a file instead)`);
    const timeoutMs = opts.timeoutMs ?? DEFAULT_COMMAND_TIMEOUT_MS;
    const wd = guestPath(opts.cwd);
    const out: Uint8Array[] = [];
    const err: Uint8Array[] = [];
    const decOut = new TextDecoder();
    const decErr = new TextDecoder();
    let res: ExecResult;
    try {
      res = await this.sbx.exec(["sh", "-c", S.RUN_SCRIPT, "_", wd, ...this.sbx.envArgv(opts.envs, argv)], {
        stdin,
        timeoutMs,
        stdout: (b) => {
          out.push(b);
          emit(decOut, opts.onStdout, b);
        },
        stderr: (b) => {
          err.push(b);
          emit(decErr, opts.onStderr, b);
        },
      });
    } finally {
      emit(decOut, opts.onStdout); // an incomplete character at the very end
      emit(decErr, opts.onStderr);
    }
    const r: CommandResult = { exitCode: res.exitCode, stdout: dec.decode(Buffer.concat(out)), stderr: dec.decode(Buffer.concat(err)) };
    if (res.timedOut) throw new TimeoutError(`command did not finish within ${timeoutMs} ms`, r);
    if (res.exitCode === S.EXIT_CANT_CHDIR && r.stderr.startsWith("sandbox: no such directory:")) throw new FileNotFoundError("directory", wd);
    if (res.exitCode !== 0) throw new CommandExitError(r);
    return r;
  }

  private async start(argv: string[], opts: CommandStartOpts): Promise<CommandHandle> {
    const id = randomBytes(8).toString("hex");
    const dir = `${S.STATE_DIR}/cmd/${id}`;
    const { out, code, err } = await this.sbx.script(S.START_SCRIPT, [dir, guestPath(opts.cwd), ...this.sbx.envArgv(opts.envs, argv)], undefined, 30_000);
    if (code !== 0) throw new SandboxError(`starting the command: ${dec.decode(err).trim() || `exit ${code}`}`);
    const pid = Number(dec.decode(out).trim());
    if (!Number.isInteger(pid)) throw new SandboxError(`starting the command: unexpected output ${JSON.stringify(dec.decode(out))}`);
    return new CommandHandle(this.sbx, pid, id, dir);
  }

  /** Background commands started in this sandbox (running and finished). */
  async list(): Promise<ProcessInfo[]> {
    const { out } = await this.sbx.script(S.LIST_SCRIPT, [S.STATE_DIR], undefined, 30_000);
    const ps: ProcessInfo[] = [];
    for (const line of dec.decode(out).split("\n")) {
      const f = line.split("\t");
      if (f.length < 4) continue;
      ps.push({ id: f[0]!, pid: Number(f[1]), running: f[2] === "-", exitCode: f[2] === "-" ? undefined : Number(f[2]), cmd: f.slice(3).join("\t") });
    }
    return ps;
  }

  /** A handle to a background command by pid. */
  async connect(pid: number): Promise<CommandHandle> {
    const { out, code } = await this.sbx.script(S.RESOLVE_PID_SCRIPT, [S.STATE_DIR, String(pid)], undefined, 30_000);
    if (code === S.EXIT_NOT_FOUND) throw new NotFoundError("command", String(pid));
    if (code !== 0) throw new SandboxError(`resolving pid ${pid}: exit ${code}`);
    const dir = dec.decode(out).trim();
    return new CommandHandle(this.sbx, pid, basename(dir), dir);
  }

  /** SIGKILL a background command (and its process group). Resolves false if it had already exited. */
  async kill(pid: number): Promise<boolean> {
    return (await this.connect(pid)).kill();
  }
}

/** @internal Decode the poll script's output: "<exit|-> <outEnd> <errEnd>\n" + stdout + stderr. */
export function parsePoll(out: Uint8Array, outOff: number, errOff: number): { exitCode?: number; stdout: Uint8Array; stderr: Uint8Array; truncated: boolean } {
  const nl = out.indexOf(10);
  const f = nl >= 0 ? dec.decode(out.subarray(0, nl)).trim().split(/\s+/) : [];
  if (f.length !== 3) throw new SandboxError(`malformed poll output ${JSON.stringify(dec.decode(out.subarray(0, 80)))}`);
  const exitCode = f[0] === "-" ? undefined : Number(f[0]);
  let nOut = Math.max(Number(f[1]) - outOff, 0);
  let nErr = Math.max(Number(f[2]) - errOff, 0);
  const body = out.subarray(nl + 1);
  let truncated = false;
  if (body.length < nOut + nErr) {
    nOut = Math.min(nOut, body.length);
    nErr = body.length - nOut;
    truncated = true;
  }
  if (nOut >= S.MAX_POLL_CHUNK || nErr >= S.MAX_POLL_CHUNK) truncated = true;
  return { exitCode, stdout: body.subarray(0, nOut), stderr: body.subarray(nOut, nOut + nErr), truncated };
}

/** A background command. */
export class CommandHandle {
  private out: Uint8Array[] = [];
  private err: Uint8Array[] = [];
  private outLen = 0;
  private errLen = 0;
  private code?: number;
  /**
   * Polls take turns: each reads from the offsets the one before it left, so overlapping poll()
   * and wait() calls never fetch (and append) the same bytes twice.
   */
  private turn: Promise<unknown> = Promise.resolve();

  /** @internal */
  constructor(
    private readonly sbx: Sandbox,
    /** Process group leader's pid in the sandbox. */
    readonly pid: number,
    /** Name of the command's state directory. */
    readonly id: string,
    private readonly dir: string,
  ) {}

  /** Standard output received so far. */
  get stdout(): string {
    return dec.decode(Buffer.concat(this.out));
  }
  get stderr(): string {
    return dec.decode(Buffer.concat(this.err));
  }
  /** The exit code once known. */
  get exitCode(): number | undefined {
    return this.code;
  }

  private pollOnce(waitTenths: number): Promise<number | undefined> {
    const run = this.turn.then(() => this.fetch(waitTenths));
    this.turn = run.catch(() => {}); // a failed poll doesn't block the next one
    return run;
  }

  private async fetch(waitTenths: number): Promise<number | undefined> {
    if (this.code !== undefined) return this.code;
    const o = this.outLen;
    const e = this.errLen;
    const { out, code } = await this.sbx.script(S.POLL_SCRIPT, [this.dir, String(o), String(e), String(waitTenths), String(S.MAX_POLL_CHUNK)], undefined, 60_000);
    if (code === S.EXIT_NOT_FOUND) throw new NotFoundError("command", String(this.pid));
    const p = parsePoll(out, o, e);
    if (p.stdout.length) {
      this.out.push(p.stdout);
      this.outLen += p.stdout.length;
    }
    if (p.stderr.length) {
      this.err.push(p.stderr);
      this.errLen += p.stderr.length;
    }
    if (p.exitCode !== undefined && !p.truncated) this.code = p.exitCode;
    return this.code;
  }

  /** Fetch new output; resolves the exit code, or undefined while it runs. */
  async poll(): Promise<number | undefined> {
    return this.pollOnce(0);
  }

  /**
   * Wait for the command to exit, passing output to the callbacks as it arrives
   * (about every 2 s), starting with output fetched earlier. Output a concurrent
   * poll() fetches is delivered too, once and in order. Rejects with
   * CommandExitError on a non-zero exit.
   */
  async wait(opts: { onStdout?: (data: string) => void; onStderr?: (data: string) => void } = {}): Promise<CommandResult> {
    // The callbacks are fed from the handle's accumulated chunks, from where this wait last left
    // off: first whatever arrived before it (via poll), then everything new, whichever call fetched it.
    const decOut = new TextDecoder();
    const decErr = new TextDecoder();
    let nOut = 0;
    let nErr = 0;
    const deliver = () => {
      for (; nOut < this.out.length; nOut++) emit(decOut, opts.onStdout, this.out[nOut]);
      for (; nErr < this.err.length; nErr++) emit(decErr, opts.onStderr, this.err[nErr]);
    };
    deliver();
    for (;;) {
      let code: number | undefined;
      try {
        code = await this.pollOnce(20);
      } finally {
        deliver();
      }
      if (code !== undefined) {
        emit(decOut, opts.onStdout); // an incomplete character at the very end
        emit(decErr, opts.onStderr);
        const r: CommandResult = { exitCode: code, stdout: this.stdout, stderr: this.stderr };
        if (code !== 0) throw new CommandExitError(r);
        return r;
      }
    }
  }

  /** SIGKILL the command's process group; the exit code becomes 137. Resolves false if it had already exited. */
  async kill(): Promise<boolean> {
    const { out, code } = await this.sbx.script(S.KILL_SCRIPT, [this.dir, "KILL", "137"], undefined, 30_000);
    if (code === S.EXIT_NOT_FOUND) throw new NotFoundError("command", String(this.pid));
    return dec.decode(out).trim() === "1";
  }
}

