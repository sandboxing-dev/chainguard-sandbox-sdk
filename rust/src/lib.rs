//! Simple Chainguard Sandbox SDK for Rust: create a sandbox on Chainguard Workspaces, run commands
//! in it, move files in and out, and delete it. The API is shaped like the E2B, Vercel Sandbox and
//! Modal SDKs, and matches the Go, Python and TypeScript SDKs.
//!
//! **Unofficial.** This SDK isn't affiliated with or supported by Chainguard. It's compatible with
//! `chainctl` 0.2.398 and the Sessions API it uses.
//!
//! ```no_run
//! use chainguard_sandbox::{CreateOptions, Sandbox};
//!
//! #[tokio::main]
//! async fn main() -> chainguard_sandbox::Result<()> {
//!     let out = Sandbox::with(CreateOptions { packages: Some(vec!["bash".into(), "python-3.13".into()]), ..Default::default() }, async |sbx| {
//!         let r = sbx.commands.run("python3 -c 'print(2+2)'").await?;
//!         sbx.files.write("notes/hello.txt", "hi").await?;
//!         Ok(r.stdout)
//!     })
//!     .await?; // the sandbox is deleted here
//!     print!("{out}"); // 4
//!     Ok(())
//! }
//! ```
//!
//! Programs without an async runtime use [`blocking`].
//!
//! The first call opens your browser to log in to Chainguard; the login is saved and shared with
//! the Go, Python and TypeScript SDKs. Workspaces must be turned on for your organization once
//! ([`enable_workspaces`], or `chainguard-sandbox enable`).
//!
//! The layers:
//!
//! - [`Sandbox`], [`Commands`], [`Files`]: the simple sandbox API.
//! - [`workspaces`]: the lower-level client (sessions, exec, login, tokens, the platform API).

#![warn(missing_debug_implementations)]

/// `Debug` that prints the type name only (for types holding callbacks or tokens).
macro_rules! opaque_debug {
    ($($t:ty),* $(,)?) => {$(
        impl std::fmt::Debug for $t {
            fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                f.debug_struct(stringify!($t)).finish_non_exhaustive()
            }
        }
    )*};
}
