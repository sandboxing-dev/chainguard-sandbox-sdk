#: The toolchain a sandbox gets by default: a shell, core tools, git, curl, jq,
#: Python and Node.js. Names are Chainguard (Wolfi) package names.
DEFAULT_PACKAGES: list[str] = ["bash", "coreutils", "curl", "git", "jq", "python-3.13", "nodejs-22"]
#: Where commands run and relative paths resolve.
DEFAULT_WORKDIR = "/work"
#: Default limit for a foreground command, in seconds (0 or None means no limit).
DEFAULT_COMMAND_TIMEOUT = 60.0

_LABEL_PREFIX = "/chainguard-sandbox/"


def _guest_path(p: str | None) -> str:
    if not p:
        return DEFAULT_WORKDIR
    return posixpath.normpath(p) if posixpath.isabs(p) else posixpath.normpath(posixpath.join(DEFAULT_WORKDIR, p))


def _wrap(e: BaseException) -> BaseException:
    """Map library/transport errors to sandbox errors."""
    if isinstance(e, _LibOutcomeUnknown):
        return OutcomeUnknownError(str(e), e.cause)
    if is_guest_held(e):
        return SandboxBusyError(f"another client (an interactive shell) is attached to this sandbox; commands run once it detaches ({e.details()})")  # pyright: ignore[reportAttributeAccessIssue]
    if isinstance(e, grpc.RpcError):
        if e.code() == grpc.StatusCode.PERMISSION_DENIED and "not entitled to Chainguard Workspaces" in (e.details() or ""):
            return WorkspacesNotEnabledError(
                "Workspaces is not turned on for this organization; an owner can turn it on with "
                f"enable_workspaces() or `chainguard-sandbox enable` ({e.details()})")
        if e.code() == grpc.StatusCode.RESOURCE_EXHAUSTED:
            return LimitReachedError(f"session limit reached; kill an existing sandbox first ({e.details()})")
        if e.code() == grpc.StatusCode.NOT_FOUND:
            return SandboxNotFoundError("sandbox", e.details() or "")
        return SandboxError(f"{e.code().name}: {e.details()}")
    return e


def _script_error(code: int, path: str, stderr: bytes) -> SandboxError:
    if code == S.EXIT_NOT_FOUND:
        return FileNotFoundError("path", path)
    if code == S.EXIT_IS_DIR:
        return InvalidPathError(path, "is a directory")
    if code == S.EXIT_NOT_DIR:
        return InvalidPathError(path, "not a directory")
    return SandboxError(f"{path}: {stderr.decode(errors='replace').strip() or f'exit {code}'}")


def _yaml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def environment_document(packages: Sequence[str] | None = None, egress: Sequence[str] | None = None,
                         egress_policy: str = "deny") -> bytes:
    """The environment document Sandbox.create sends (packages + egress policy)."""
    pkgs = DEFAULT_PACKAGES if packages is None else list(packages)
    hosts = ["*"] if egress is None else list(egress)
    lines = ["# Generated by chainguard-sandbox-sdk.", "version: 1", "environment:", "  packages:"]
    lines += [f"    - {_yaml_str(p)}" for p in pkgs]
    lines += ["checks:", "  develop:", "    network:"]
    lines += ["      egress:" + (" []" if not hosts else "")] + [f"        - {_yaml_str(h)}" for h in hosts]
    lines += [f"      policy: {_yaml_str(egress_policy or 'deny')}"]
    return ("\n".join(lines) + "\n").encode()


@dataclass
class SandboxInfo:
    sandbox_id: str
    name: str
    display_name: str
    #: "creating", "running", "paused" or "stopped".
    state: str
    region: str
    created_at: _dt.datetime | None
    #: When a paused sandbox is discarded, if set.
    expires_at: _dt.datetime | None
    cpu_count: int
    memory_mb: int


def _info(s: spb.Session) -> SandboxInfo:
    state = {spb.CREATING: "creating", spb.ATTACHED: "running", spb.IDLE: "running", spb.PARKED: "paused"}.get(s.phase, "stopped")
    ts = lambda t: t.ToDatetime(tzinfo=_dt.timezone.utc) if t.seconds or t.nanos else None  # noqa: E731
    return SandboxInfo(s.short_id, s.name, s.display_name, state, s.region, ts(s.create_time), ts(s.expire_time),
                       s.max_resource_class.cpus, s.max_resource_class.memory_mib)


class _ClassOrInstance:
    """A method usable on the class (with a sandbox ID first) or on an instance, like E2B's."""

    def __init__(self, inst: Callable, cls: Callable, doc: str = ""):
        self._inst, self._cls = inst, cls
        self.__doc__ = doc

    def __get__(self, obj, owner):
        if obj is None:
            return functools.partial(self._cls, owner)
        return functools.partial(self._inst, obj)


class Sandbox:
    """A sandbox: one Chainguard Workspaces session with your packages.

    >>> with Sandbox.create(packages=["python-3.13"]) as sbx:
    ...     print(sbx.commands.run("python3 -c 'print(2+2)'").stdout)
    4

    Commands run one at a time per sandbox. Durations are in seconds.
    """

    def __init__(self, client: Client, session: spb.Session, envs: dict[str, str] | None, owns_client: bool):
        self._client, self._owns = client, owns_client
        #: The short sandbox ID (8 hex characters), usable with Sandbox.connect.
        self.sandbox_id: str = session.short_id
        #: The full resource name (instances/<org>/sessions/<id>).
        self.name: str = session.name
        self._envs = dict(envs or {})
        #: Run commands: ``sbx.commands.run(...)``.
        self.commands = Commands(self)
        #: Read and write files: ``sbx.files.read(...)``.
        self.files = Files(self)

    # --- creating and finding sandboxes -----------------------------------------

    @classmethod
    def create(
        cls,
        *,
        packages: Sequence[str] | None = None,
        envs: dict[str, str] | None = None,
        name: str = "sandbox",
        egress: Sequence[str] | None = None,
        egress_policy: Literal["deny", "destroy"] = "deny",
        document: bytes | None = None,
        source: str | None = None,
        source_revision: str = "",
        start_timeout: float = 180,
        client: Client | None = None,
        instance: str | None = None,
    ) -> Sandbox:
        """Create a sandbox and return when it can run commands (about 8-20 s).

        packages: Chainguard package names (default DEFAULT_PACKAGES).
        envs: environment variables for every command (kept client-side).
        name: label; the display name becomes ``<name>/<word-word>``.
        egress / egress_policy: outbound allowlist (default ``["*"]``) and what
        happens outside it ("deny" refuses the connection, "destroy" stops the sandbox).
        document: a full environment document instead of packages/egress.
        source: a GitHub repository to start from instead of an empty /work.
        instance: the organization ID. If None, $CHAINCTL_SANDBOX_INSTANCE is used;
        if that's empty too, the organization is auto-detected when you belong
        to exactly one ($CHAINGUARD_SANDBOX_NO_DETECT_INSTANCE=1 turns that off). List IDs
        with list_organizations(), ``chainguard-sandbox orgs`` or ``chainctl iam organizations list``.

        A session the plane places on a host that never starts is deleted and
        recreated (up to 3 attempts). On failure nothing is left behind.
        """
        if "/" in name or "\n" in name or not name:
            raise ValueError("name must be non-empty without '/' or newlines")
        owns = client is None
        c = client or Client(instance=instance)
        try:
            doc = document if document is not None else environment_document(packages, egress, egress_policy)
            last: BaseException | None = None
            for _ in range(3):
                if source:
                    req = repository_session(source, source_revision)
                    req.source.fallback_document = doc
                else:
                    req = workspace_session(_LABEL_PREFIX + name, document=doc)
                try:
                    s = c.create(req)
                except grpc.RpcError as e:
                    raise _wrap(e) from e
                try:
                    s = _wait_started(c, s.name, start_timeout)
                    if s.workspace_pending:
                        _empty_upload(c, s.name)
                except _Placement as e:
                    _delete_quietly(c, s.name)
                    last = e
                    continue
                except BaseException:
                    _delete_quietly(c, s.name)
                    raise
                return cls(c, s, envs, owns)
            raise SandboxError(f"the plane could not start a guest in 3 attempts: {last}")
        except BaseException:
            if owns:
                c.close()
            raise

    @classmethod
    def connect(cls, sandbox_id: str, *, envs: dict[str, str] | None = None, client: Client | None = None,
                instance: str | None = None) -> Sandbox:
        """A handle to an existing sandbox (short ID, display name or resource name).
        A paused sandbox resumes on its first command."""
        owns = client is None
        c = client or Client(instance=instance)
        try:
            try:
                s = c.resolve(sandbox_id)
            except _LibNotFound as e:
                raise SandboxNotFoundError("sandbox", sandbox_id) from e
            except grpc.RpcError as e:
                raise _wrap(e) from e
            if s.workspace_pending:
                _empty_upload(c, s.name)
            return cls(c, s, envs, owns)
        except BaseException:
            if owns:
                c.close()
            raise

    @staticmethod
    def list(*, client: Client | None = None, instance: str | None = None) -> list[SandboxInfo]:
        """The sandboxes this package created in the instance."""
        c = client or Client(instance=instance)
        try:
            return [_info(s) for s in c.list() if s.workspace.label.startswith(_LABEL_PREFIX)]
        except grpc.RpcError as e:
            raise _wrap(e) from e
        finally:
            if client is None:
                c.close()

    # --- lifecycle ------------------------------------------------------------------

    def _kill(self) -> bool:
        try:
            return _delete_and_wait(self._client, self.name)
        finally:
            self.close()

    def _kill_by_id(cls, sandbox_id: str, *, client: Client | None = None, instance: str | None = None) -> bool:  # noqa: N805  # pyright: ignore[reportSelfClsParameterName] - bound to the class by the kill descriptor
        # No connect(): that attaches first, which fails for a sandbox that
        # never started or can't be attached to. Resolve the name and delete.
        c = client or Client(instance=instance)
        try:
            try:
                s = c.resolve(sandbox_id)
            except _LibNotFound:
                return False
            except grpc.RpcError as e:
                if e.code() == grpc.StatusCode.NOT_FOUND:
                    return False
                raise _wrap(e) from e
            return _delete_and_wait(c, s.name)
        finally:
            if client is None:
                c.close()

    kill = _ClassOrInstance(
        _kill, _kill_by_id,
        """Delete the sandbox and everything in it, and return once it is gone, so
        the session slot is free. Returns False if it was already gone.

        Raises TimeoutError if the sandbox still exists 30 s after the delete
        request (or that can't be confirmed): deletion was requested, but the
        slot may not be free yet.

        Works on the class too, ``Sandbox.kill("1a2b3c4d")`` (short ID, display
        name or resource name). That form deletes without attaching, so it also
        removes a sandbox that never started or can't be attached to.""")

    def close(self) -> None:
        """Release the connection (if this handle opened it); the sandbox keeps running."""
        if self._owns:
            self._owns = False
            self._client.close()

    def pause(self) -> None:
        """Snapshot (memory and disk) and stop the sandbox. Processes, including
        background commands, continue where they were on the next call."""
        try:
            self._client.park(self.name)
        except grpc.RpcError as e:
            raise _wrap(e) from e

    def keep_alive(self, seconds: float) -> None:
        """Hold the sandbox running (not parked when idle) for this long. There is
        no hard deadline: an idle sandbox parks after about 10 minutes."""
        try:
            self._client.heartbeat(self.name, seconds)
        except grpc.RpcError as e:
            raise _wrap(e) from e

    def get_info(self) -> SandboxInfo:
        try:
            return _info(self._client.get(self.name))
        except grpc.RpcError as e:
            if e.code() == grpc.StatusCode.NOT_FOUND:
                raise SandboxNotFoundError("sandbox", self.sandbox_id) from e
            raise _wrap(e) from e

    def is_running(self) -> bool:
        try:
            return self.get_info().state == "running"
        except SandboxNotFoundError:
            return False

    @property
    def client(self) -> Client:
        """The underlying Workspaces client, for anything this package doesn't wrap."""
        return self._client

    def __enter__(self) -> Sandbox:
        return self

    def __exit__(self, exc_type, exc, tb) -> None:
        if exc_type is None:
            self.kill()
            return
        try:  # the block's own error is the one to report
            self.kill()
        except SandboxError:
            pass

    def __repr__(self) -> str:
        return f"Sandbox(sandbox_id={self.sandbox_id!r})"

    # --- helpers -----------------------------------------------------------------------

    def _env_argv(self, extra: dict[str, str] | None, argv: list[str]) -> list[str]:
        merged = {**self._envs, **(extra or {})}
        if not merged:
            return argv
        return ["env", *(f"{k}={merged[k]}" for k in sorted(merged)), *argv]

    def _exec(self, argv: list[str], *, stdin: bytes = b"", timeout: float = 30, stdout=None, stderr=None):
        try:
            return self._client.exec(self.name, argv, no_dir=True, stdin=stdin, timeout=timeout, stdout=stdout, stderr=stderr)
        except (grpc.RpcError, _LibOutcomeUnknown) as e:
            raise _wrap(e) from e

    def _script(self, script: str, *args: str, stdin: bytes = b"", timeout: float = 0) -> tuple[bytes, int, bytes]:
        out, err = io.BytesIO(), io.BytesIO()
        res = self._exec(["sh", "-c", script, "_", *args], stdin=stdin, timeout=timeout, stdout=out, stderr=err)
        return out.getvalue(), res.exit_code, err.getvalue()


class _Placement(Exception):
    pass


def _delete_quietly(c: Client, name: str) -> None:
    try:
        c.delete(name)
    except Exception:  # noqa: BLE001 - best effort cleanup
        pass


#: Timings (seconds), as module values so tests can shorten them.
_PLACEMENT_GRACE = 30.0  # how long "starting guest failed" may show before giving up on a host
_START_POLL = 1.0  # between GetSession calls while starting
_KILL_WAIT = 30.0  # how long kill waits for the session to disappear
_KILL_POLL = 0.5  # between GetSession calls while deleting


def _deadline_passed(e: BaseException, deadline: float) -> bool:
    """Whether a get() failed because our own deadline ran out."""
    if isinstance(e, AuthTimeoutError):
        return True
    return (isinstance(e, grpc.RpcError) and e.code() == grpc.StatusCode.DEADLINE_EXCEEDED  # pyright: ignore[reportAttributeAccessIssue]
            and time.monotonic() >= deadline - 0.05)


def _wait_started(c: Client, name: str, limit: float) -> spb.Session:
    """Poll until the guest has started. limit bounds the whole wait, each
    GetSession call included: a call that stalls is cut off at the deadline,
    and an answer that arrives after it is never reported as a start in time."""
    t0 = time.monotonic()
    deadline = t0 + limit
    last: spb.Session | None = None

    def expired() -> TimeoutError:
        detail = f" ({spb.Phase.Name(last.phase)}: {last.message})" if last is not None else ""
        return TimeoutError(f"the guest did not start within {limit:g}s{detail}")

    while True:
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            raise expired()
        try:
            s = c.get(name, timeout=remaining)
        except (grpc.RpcError, AuthTimeoutError) as e:
            if _deadline_passed(e, deadline):
                raise expired() from e
            raise _wrap(e) from e
        if time.monotonic() > deadline:
            raise expired()
        last = s
        if s.HasField("guest_started_time"):
            return s
        if "starting guest failed" in s.message and time.monotonic() - t0 > _PLACEMENT_GRACE:
            raise _Placement(s.message)
        time.sleep(max(min(_START_POLL, deadline - time.monotonic()), 0))


def _delete_and_wait(c: Client, name: str) -> bool:
    """Send the delete request and wait until the session is gone. False if
    there was none. Raises TimeoutError if it can't be confirmed gone."""
    try:
        c.delete(name)
    except grpc.RpcError as e:
        if e.code() == grpc.StatusCode.NOT_FOUND:
            return False
        raise _wrap(e) from e
    # Deletion is asynchronous (the session disappears 1-8 s later). Each check
    # runs under the deadline, so a stalled call can't stretch the wait.
    deadline = time.monotonic() + _KILL_WAIT
    failure: BaseException | None = None
    while True:
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            break
        try:
            c.get(name, timeout=remaining)
            failure = None
        except (grpc.RpcError, AuthTimeoutError) as e:
            if isinstance(e, grpc.RpcError) and e.code() == grpc.StatusCode.NOT_FOUND:
                return True
            if not _deadline_passed(e, deadline):  # a check cut off by the deadline keeps the last answer
                failure = e
        time.sleep(max(min(_KILL_POLL, deadline - time.monotonic()), 0))
    if failure is not None:
        raise TimeoutError(f"could not confirm the sandbox is gone within {_KILL_WAIT:g}s (last check: {_wrap(failure)})") from failure
    raise TimeoutError(f"the sandbox still exists {_KILL_WAIT:g}s after the delete request")


def _empty_upload(c: Client, name: str) -> None:
    """Complete the required first attach with an empty tree (exec is refused
    until a shell attach has uploaded the workspace)."""
    try:
        complete_first_attach(c, name, timeout=120)
    except builtins.TimeoutError as e:
        raise TimeoutError("the first attach did not complete") from e
    except (grpc.RpcError, FirstAttachError) as e:
        raise SandboxError(f"completing the first attach: {_wrap(e)}") from e


