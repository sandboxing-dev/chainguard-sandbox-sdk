def _decoder() -> codecs.IncrementalDecoder:
    """Output arrives in arbitrary chunks, so a multi-byte UTF-8 character can
    be split across two of them. An incremental decoder holds the incomplete
    tail back and returns the character with the next chunk."""
    return codecs.getincrementaldecoder("utf-8")(errors="replace")


class _Tee:
    def __init__(self, cb: Callable[[str], object] | None):
        self.buf, self.cb = io.BytesIO(), cb
        self._dec = _decoder()

    def write(self, b: bytes) -> int:
        self.buf.write(b)
        if self.cb:
            s = self._dec.decode(b)
            if s:
                self.cb(s)
        return len(b)

    def finish(self) -> None:
        """Deliver what the decoder still holds (an incomplete character at the end)."""
        if self.cb:
            s = self._dec.decode(b"", final=True)
            if s:
                self.cb(s)

    def text(self) -> str:
        return self.buf.getvalue().decode(errors="replace")


@dataclass
class ProcessInfo:
    pid: int
    id: str
    cmd: str
    running: bool
    exit_code: int | None


class Commands:
    """``sbx.commands``: run commands in the sandbox."""

    def __init__(self, sbx: Sandbox):
        self._sbx = sbx

    @staticmethod
    def _argv(cmd: str | Sequence[str]) -> list[str]:
        if isinstance(cmd, str):
            return ["bash", "-lc", cmd]
        argv = list(cmd)
        if not argv:
            raise ValueError("empty command")
        return argv

    @overload
    def run(self, cmd: str | Sequence[str], *, background: Literal[False] = False, cwd: str | None = None,
            envs: dict[str, str] | None = None, timeout: float | None = DEFAULT_COMMAND_TIMEOUT,
            stdin: bytes | str | None = None, on_stdout: Callable[[str], object] | None = None,
            on_stderr: Callable[[str], object] | None = None) -> CommandResult: ...

    @overload
    def run(self, cmd: str | Sequence[str], *, background: Literal[True], cwd: str | None = None,
            envs: dict[str, str] | None = None, timeout: float | None = DEFAULT_COMMAND_TIMEOUT,
            stdin: bytes | str | None = None, on_stdout: Callable[[str], object] | None = None,
            on_stderr: Callable[[str], object] | None = None) -> CommandHandle: ...

    def run(self, cmd, *, background=False, cwd=None, envs=None, timeout=DEFAULT_COMMAND_TIMEOUT, stdin=None,  # pyright: ignore[reportInconsistentOverload]
            on_stdout=None, on_stderr=None):
        """Run a command and wait for it.

        cmd: a string (run with bash, so shell syntax works) or an argv list (no shell).
        background=True starts it detached and returns a CommandHandle at once
        (timeout, stdin and the callbacks don't apply; pass callbacks to handle.wait()).

        Raises CommandExitError (with .exit_code/.stdout/.stderr) on a non-zero
        exit, TimeoutError when timeout seconds pass (None or 0: no limit), and
        FileNotFoundError if cwd doesn't exist.
        """
        argv = self._argv(cmd)
        if background:
            return self._start(argv, cwd, envs)
        data = stdin.encode() if isinstance(stdin, str) else (stdin or b"")
        if len(data) > 16 << 20:
            raise ValueError(f"stdin is {len(data)} bytes; the limit is 16 MiB (write a file instead)")
        wd = _guest_path(cwd)
        out, err = _Tee(on_stdout), _Tee(on_stderr)
        try:
            res = self._sbx._exec(["sh", "-c", S.RUN_SCRIPT, "_", wd, *self._sbx._env_argv(envs, argv)], stdin=data,
                                  timeout=timeout or 0, stdout=out, stderr=err)
        finally:
            out.finish()
            err.finish()
        r = CommandResult(res.exit_code, out.text(), err.text())
        if res.timed_out:
            raise TimeoutError(f"command did not finish within {timeout:g}s", r)
        if res.exit_code == S.EXIT_CANT_CHDIR and r.stderr.startswith("sandbox: no such directory:"):
            raise FileNotFoundError("directory", wd)
        if res.exit_code != 0:
            raise CommandExitError(r)
        return r

    def _start(self, argv: list[str], cwd: str | None, envs: dict[str, str] | None) -> CommandHandle:
        cid = secrets.token_hex(8)
        d = f"{S.STATE_DIR}/cmd/{cid}"
        out, code, err = self._sbx._script(S.START_SCRIPT, d, _guest_path(cwd), *self._sbx._env_argv(envs, argv), timeout=30)
        if code != 0:
            raise SandboxError(f"starting the command: {err.decode(errors='replace').strip() or f'exit {code}'}")
        try:
            pid = int(out.strip())
        except ValueError:
            raise SandboxError(f"starting the command: unexpected output {out!r}") from None
        return CommandHandle(self._sbx, pid, cid, d)

    def list(self) -> list[ProcessInfo]:
        """Background commands started in this sandbox (running and finished)."""
        out, _, _ = self._sbx._script(S.LIST_SCRIPT, S.STATE_DIR, timeout=30)
        ps = []
        for line in out.decode(errors="replace").splitlines():
            f = line.split("\t", 3)
            if len(f) != 4:
                continue
            code = int(f[2]) if f[2] != "-" else None
            ps.append(ProcessInfo(int(f[1]), f[0], f[3], f[2] == "-", code))
        return ps

    def connect(self, pid: int) -> CommandHandle:
        """A handle to a background command by pid."""
        out, code, _ = self._sbx._script(S.RESOLVE_PID_SCRIPT, S.STATE_DIR, str(pid), timeout=30)
        if code == S.EXIT_NOT_FOUND:
            raise NotFoundError("command", str(pid))
        if code != 0:
            raise SandboxError(f"resolving pid {pid}: exit {code}")
        d = out.decode().strip()
        return CommandHandle(self._sbx, pid, posixpath.basename(d), d)

    def kill(self, pid: int) -> bool:
        """SIGKILL a background command (and its process group). False if it had already exited."""
        return self.connect(pid).kill()


class CommandHandle:
    """A background command. Iterating yields ``(stdout, stderr)`` chunks until it exits."""

    def __init__(self, sbx: Sandbox, pid: int, cid: str, d: str):
        self._sbx = sbx
        #: Process group leader's pid in the sandbox.
        self.pid = pid
        #: Name of the command's state directory.
        self.id = cid
        self._dir = d
        # _poll_lock makes polls take turns: each reads from the offsets the one
        # before it left, so overlapping poll() and wait() calls never fetch (and
        # append) the same bytes twice. _lock guards the fields below.
        self._poll_lock = threading.Lock()
        self._lock = threading.Lock()
        self._out, self._err = bytearray(), bytearray()
        self._exit: int | None = None

    @property
    def stdout(self) -> str:
        """Standard output received so far."""
        return bytes(self._out).decode(errors="replace")

    @property
    def stderr(self) -> str:
        return bytes(self._err).decode(errors="replace")

    @property
    def exit_code(self) -> int | None:
        """The exit code once known."""
        return self._exit

    def _poll(self, wait_tenths: int) -> int | None:
        with self._poll_lock:
            with self._lock:
                if self._exit is not None:
                    return self._exit
                o, e = len(self._out), len(self._err)
            out, code, _ = self._sbx._script(S.POLL_SCRIPT, self._dir, str(o), str(e), str(wait_tenths), str(S.MAX_POLL_CHUNK), timeout=60)
            if code == S.EXIT_NOT_FOUND:
                raise NotFoundError("command", str(self.pid))
            exit_code, new_out, new_err, truncated = parse_poll(out, o, e)
            with self._lock:
                self._out += new_out
                self._err += new_err
                if exit_code is not None and not truncated:
                    self._exit = exit_code
                return self._exit

    def poll(self) -> int | None:
        """Fetch new output; return the exit code, or None while it runs."""
        return self._poll(0)

    def _reader(self) -> Callable[[bool], tuple[str, str]]:
        """A function returning the (stdout, stderr) text accumulated since its
        last call, whichever call fetched it. Pass True on the last call to get
        an incomplete character at the very end too."""
        sent = [0, 0]
        dec_out, dec_err = _decoder(), _decoder()

        def take(final: bool = False) -> tuple[str, str]:
            with self._lock:
                o, e = bytes(self._out[sent[0]:]), bytes(self._err[sent[1]:])
                sent[0], sent[1] = len(self._out), len(self._err)
            return dec_out.decode(o, final), dec_err.decode(e, final)

        return take

    def wait(self, on_stdout: Callable[[str], object] | None = None,
             on_stderr: Callable[[str], object] | None = None) -> CommandResult:
        """Wait for the command to exit, passing output to the callbacks as it
        arrives (about every 2 s), starting with output fetched earlier. Output
        a concurrent poll() fetches is delivered too, once and in order.
        Raises CommandExitError on a non-zero exit."""
        take = self._reader()

        def deliver(final: bool = False) -> None:
            o, e = take(final)
            if on_stdout and o:
                on_stdout(o)
            if on_stderr and e:
                on_stderr(e)

        deliver()
        while True:
            code = self._poll(20)
            deliver(code is not None)
            if code is not None:
                r = CommandResult(code, self.stdout, self.stderr)
                if code != 0:
                    raise CommandExitError(r)
                return r

    def __iter__(self) -> Iterator[tuple[str | None, str | None]]:
        take = self._reader()
        while True:
            code = self._poll(20)
            o, e = take(code is not None)
            if o or e:
                yield (o or None, e or None)
            if code is not None:
                return

    def kill(self) -> bool:
        """SIGKILL the command's process group; the exit code becomes 137.
        False if it had already exited."""
        out, code, _ = self._sbx._script(S.KILL_SCRIPT, self._dir, "KILL", "137", timeout=30)
        if code == S.EXIT_NOT_FOUND:
            raise NotFoundError("command", str(self.pid))
        return out.strip() == b"1"

    def __repr__(self) -> str:
        return f"CommandHandle(pid={self.pid})"


def parse_poll(out: bytes, out_off: int, err_off: int) -> tuple[int | None, bytes, bytes, bool]:
    """Decode the poll script's output: "<exit|-> <outEnd> <errEnd>\\n" + stdout + stderr."""
    nl = out.find(b"\n")
    f = out[:nl].split() if nl >= 0 else []
    if len(f) != 3:
        raise SandboxError(f"malformed poll output {out[:80]!r}")
    code = None if f[0] == b"-" else int(f[0])
    n_out, n_err = max(int(f[1]) - out_off, 0), max(int(f[2]) - err_off, 0)
    body = out[nl + 1:]
    truncated = False
    if len(body) < n_out + n_err:
        n_out = min(n_out, len(body))
        n_err = len(body) - n_out
        truncated = True
    if n_out >= S.MAX_POLL_CHUNK or n_err >= S.MAX_POLL_CHUNK:
        truncated = True
    return code, body[:n_out], body[n_out:n_out + n_err], truncated


