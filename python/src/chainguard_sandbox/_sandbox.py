@dataclass
class WriteInfo:
    name: str
    path: str
    type: str = "file"


@dataclass
class EntryInfo:
    name: str
    path: str
    #: "file", "dir" or "symlink".
    type: str
    size: int
    mode: int
    #: e.g. "rwxr-xr-x".
    permissions: str
    owner: str
    group: str
    modified_time: _dt.datetime
    symlink_target: str | None = None


def _perm_string(mode: int) -> str:
    return "".join(c if mode & (1 << (8 - i)) else "-" for i, c in enumerate("rwxrwxrwx"))


def parse_entries(out: bytes, base: str = "") -> list[EntryInfo]:
    """Decode stat lines: "<type>\\t<size> <mode> <user> <group> <mtime>\\t<link>\\t<path>"."""
    es = []
    for line in out.decode(errors="replace").splitlines():
        if not line:
            continue
        f = line.split("\t", 3)
        st = f[1].split() if len(f) == 4 else []
        if len(st) != 5:
            raise SandboxError(f"malformed entry {line!r}")
        p = posixpath.join(base, f[3]) if base else f[3]
        mode = int(st[1], 8) & 0o777
        es.append(EntryInfo(posixpath.basename(p), p, f[0], int(st[0]), mode, _perm_string(mode), st[2], st[3],
                            _dt.datetime.fromtimestamp(int(st[4]), _dt.timezone.utc), f[2] or None))
    return es


class Files:
    """``sbx.files``: the sandbox filesystem. Relative paths resolve against /work."""

    def __init__(self, sbx: Sandbox):
        self._sbx = sbx

    def _run(self, script: str, *args: str, stdin: bytes = b"", path: str = "") -> bytes:
        out, code, err = self._sbx._script(script, *args, stdin=stdin)
        if code != 0:
            raise _script_error(code, path or (args[0] if args else ""), err)
        return out

    @overload
    def read(self, path: str, format: Literal["text"] = "text") -> str: ...
    @overload
    def read(self, path: str, format: Literal["bytes"]) -> bytes: ...

    def read(self, path, format="text"):
        """A file's contents, as text (UTF-8) or bytes. Raises FileNotFoundError if missing."""
        b = self._run(S.READ_SCRIPT, _guest_path(path))
        return b if format == "bytes" else b.decode(errors="replace")

    def write(self, path: str, data: str | bytes | IO[bytes]) -> WriteInfo:
        """Create or replace a file atomically (mode 0644), creating parent
        directories. Any size works (over 15 MiB is staged in pieces)."""
        return self._write(path, data, 0o644)

    def _write(self, path: str, data, mode: int) -> WriteInfo:
        gp = _guest_path(path)
        b = data.encode() if isinstance(data, str) else data.read() if hasattr(data, "read") else bytes(data)
        if len(b) <= S.MAX_STDIN_PER_EXEC:
            try:
                self._sbx._client.write_file(self._sbx.name, gp, b, mode)
            except IsADirectoryError as e:
                raise InvalidPathError(gp, "is a directory") from e
            except _LibExitError as e:
                raise SandboxError(str(e)) from e
            except (grpc.RpcError, _LibOutcomeUnknown) as e:
                raise _wrap(e) from e
        else:
            tmp = self._stage(b)
            self._run(S.FINISH_SCRIPT, tmp, gp, f"{mode & 0o777:o}", path=gp)
        return WriteInfo(posixpath.basename(gp), gp)

    def _stage(self, b: bytes) -> str:
        tmp = f"{S.STATE_DIR}/upload/{secrets.token_hex(8)}"
        step = S.MAX_STDIN_PER_EXEC
        for off in range(0, max(len(b), 1), step):
            self._run(S.APPEND_SCRIPT, tmp, "trunc" if off == 0 else "append", stdin=b[off:off + step], path=tmp)
        return tmp

    def _untar(self, tgz: bytes, d: str) -> None:
        if len(tgz) > S.MAX_STDIN_PER_EXEC:
            self._run(S.UNTAR_SCRIPT, self._stage(tgz), d, path=d)
        else:
            self._run(S.UNTAR_SCRIPT, "-", d, stdin=tgz, path=d)

    def write_files(self, files: Sequence[dict]) -> list[WriteInfo]:
        """Write several files in one upload: ``[{"path": ..., "data": ..., "mode": 0o755}]``
        (mode optional, default 0644). Parent directories are created."""
        buf = io.BytesIO()
        infos = []
        with tarfile.open(fileobj=buf, mode="w:gz", format=tarfile.PAX_FORMAT) as tf:
            for f in files:
                gp = _guest_path(f["path"])
                if gp == "/":
                    raise ValueError(f"invalid file path {f['path']!r}")
                data = f["data"].encode() if isinstance(f["data"], str) else bytes(f["data"])
                ti = tarfile.TarInfo(gp.lstrip("/"))
                ti.size, ti.mode, ti.mtime = len(data), f.get("mode", 0o644) & 0o777 or 0o644, int(time.time())
                ti.uid = ti.gid = 0
                tf.addfile(ti, io.BytesIO(data))
                infos.append(WriteInfo(posixpath.basename(gp), gp))
        self._untar(buf.getvalue(), "/")
        return infos

    def list(self, path: str = ".") -> list[EntryInfo]:
        """Entries of a directory (one level), sorted by name."""
        gp = _guest_path(path)
        return parse_entries(self._run(S.LIST_DIR_SCRIPT, gp), gp)

    def exists(self, path: str) -> bool:
        """Whether a path exists (a dangling symlink counts)."""
        return self._sbx._script(S.EXISTS_SCRIPT, _guest_path(path))[1] == 0

    def get_info(self, path: str) -> EntryInfo:
        """Describe a path without following a final symlink."""
        es = parse_entries(self._run(S.INFO_SCRIPT, _guest_path(path)))
        if len(es) != 1:
            raise SandboxError(f"unexpected stat output for {path}")
        return es[0]

    def make_dir(self, path: str) -> bool:
        """Create a directory and its parents. False if it already existed."""
        return self._run(S.MAKE_DIR_SCRIPT, _guest_path(path)).strip() == b"1"

    def remove(self, path: str) -> None:
        """Delete a file or directory tree. Raises FileNotFoundError if missing."""
        self._run(S.REMOVE_SCRIPT, _guest_path(path))

    def rename(self, old_path: str, new_path: str) -> EntryInfo:
        """Move a file or directory (creating the destination's parents); describes the result."""
        es = parse_entries(self._run(S.RENAME_SCRIPT, _guest_path(old_path), _guest_path(new_path)))
        if len(es) != 1:
            raise SandboxError(f"unexpected stat output for {new_path}")
        return es[0]

    def upload(self, local_path: str | os.PathLike, remote_path: str) -> WriteInfo:
        """Copy a local file into the sandbox (keeping its permission bits)."""
        mode = os.stat(local_path).st_mode & 0o777
        with open(local_path, "rb") as f:
            return self._write(remote_path, f.read(), mode)

    def download(self, remote_path: str, local_path: str | os.PathLike) -> None:
        """Copy a file from the sandbox, creating local parent directories."""
        data = self.read(remote_path, format="bytes")
        os.makedirs(os.path.dirname(os.path.abspath(local_path)), exist_ok=True)
        with open(local_path, "wb") as f:
            f.write(data)

    def upload_dir(self, local_dir: str | os.PathLike, remote_dir: str) -> None:
        """Copy a local directory tree into remote_dir (created if missing) as one
        tar. Symlinks are copied as links; files are owned by root."""
        self._untar(tar_gz_dir(os.fspath(local_dir)), _guest_path(remote_dir))

    def download_dir(self, remote_dir: str, local_dir: str | os.PathLike) -> None:
        """Copy a directory tree from the sandbox into local_dir. Nothing is
        written outside it: absolute names, "..", and symbolic links that lead
        outside are refused."""
        tgz = self._run(S.TAR_SCRIPT, _guest_path(remote_dir))
        os.makedirs(local_dir, exist_ok=True)
        with tarfile.open(fileobj=io.BytesIO(tgz), mode="r:gz") as tf:
            try:
                tf.extractall(local_dir, filter="data")
            except tarfile.FilterError as e:
                raise SandboxError(f"refusing archive entry: {e}") from e
